const catalog = Object.fromEntries(Object.entries(entries).map(([op, groups]) => [
  op, new Map(groups.flatMap(([ids, en, ru]) => ids.map(id => [id, {en, ru}]))),
]));

export function commandDescription(command, language) {
  const description = catalog[command?.op]?.get(command.kind);
  return description?.[language] ?? description?.en ?? '';
}
